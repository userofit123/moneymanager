// the text itself, or with its first letter in the other case
function look(s) {
  let r = EXACT[s];
  if (r === undefined) r = EXACT[s.charAt(0).toLowerCase() + s.slice(1)];
  if (r === undefined) r = EXACT[s.charAt(0).toUpperCase() + s.slice(1)];
  return r;
}
function find(s) {
  const r = look(s);
  if (r !== undefined) return r;
  for (const [re, fn] of RULES) { const m = s.match(re); if (m) return fn(...m.slice(1)).replace(DATE, (x, d, mo, y) => heDate(d, mo, y)); }
  // numbers, dates and months become {}, {d} and {m}, and are put back into the Hebrew in the same order
  const ds = [], ns = [], ms = [];
  const key = s.replace(DATE, (x, d, mo, y) => { ds.push(heDate(d, mo, y)); return "{d}"; })
    .replace(MONTH, (m) => { ms.push(heMonth(m)); return "{m}"; })
    .replace(NUM, (m) => { ns.push(m); return "{}"; });
  if (!ds.length && !ns.length && !ms.length) return undefined;
  const t = look(key);
  if (t === undefined) return undefined;
  let di = 0, ni = 0, mi = 0;
  return t.replace(/\{d\}|\{\}|\{m\}/g, (x) => (x == "{d}" ? ds[di++] || "" : x == "{m}" ? ms[mi++] || "" : ns[ni++] || ""));
}

const cache = new Map();
// heSaved("Edited category") → "עריכת קטגוריה". Spaces around the text are kept; text with no English letters, or not known, comes back as it is.
export function heSaved(s) {
  if (typeof s !== "string") return s;
  const [, pre, core, post] = s.match(/^(\s*)([\s\S]*?)(\s*)$/);
  if (!core || !/[A-Za-z]/.test(core)) return s;
  let r = cache.get(core);
  if (r === undefined) { r = find(core) ?? null; cache.set(core, r); }
  return r === null ? s : pre + r + post;
}

// Builds src/core/he-legacy.js from the current app's Hebrew files (web/he-core.js, he-text.js, he-rules.js).
// The Vue app uses it only for English text that comes from saved data or the server (the change history, sync messages),
// which the current app also translates this way. Run: node scripts/sync-he.mjs (test/he-legacy.test.js checks it is up to date).
import fs from "node:fs";
const WEB = new URL("../../web/", import.meta.url), OUT = new URL("../src/core/he-legacy.js", import.meta.url);
export function build() {
  const rd = (f) => fs.readFileSync(new URL(f, WEB), "utf8");
  return [
    "/* Generated by scripts/sync-he.mjs from web/he-core.js, he-text.js and he-rules.js. Do not edit by hand. */",
    "/* eslint-disable */",
    "const window = {}; let HE; let S = null;",
    "export function setProfileState(s) { S = s; }",
    rd("he-core.js"), "HE = window.HE;", rd("he-text.js"), rd("he-rules.js"),
    "export default HE;", "",
  ].join("\n");
}
if (process.argv[1] && new URL(import.meta.url).pathname === fs.realpathSync(process.argv[1])) { fs.writeFileSync(OUT, build()); console.log("wrote", OUT.pathname); }
